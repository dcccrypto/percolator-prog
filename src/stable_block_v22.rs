/// True when `mint` is a denylisted stablecoin mint.
#[inline]
pub fn is_stable_mint(mint: &[u8; 32]) -> bool {
    STABLE_MINTS.iter().any(|m| m.as_ref() == mint.as_slice())
}

/// True when `feed` is a denylisted stablecoin / USD feed id.
#[inline]
pub fn is_stable_feed(feed: &[u8; 32]) -> bool {
    STABLE_PYTH_FEED_IDS.iter().any(|f| f == feed)
}

/// True when the oracle legs make a stablecoin the tracked price: the PRIMARY leg (leg 0, the
/// numerator) is a denylisted feed. A stable as leg 1 / leg 2 only converts the quote currency
/// (X/USD divided by USDC/USD = X/USDC) and stays allowed. Refusing on leg 0 also closes the
/// dummy-leg cross (USDC/USD divided by some near-constant feed). Residual: an inverse perp priced
/// as USDC/USD divided by X/USD is refused (use the `invert` flag on X/USD instead), and a pegged
/// feed that is NOT on the list can still be used as leg 0 (see the PR "Limits" section).
pub fn oracle_primary_leg_is_stable(count: u8, feeds: &[[u8; 32]]) -> bool {
    count != 0 && count as usize <= feeds.len() && is_stable_feed(&feeds[0])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mints() {
        let usdc = pubkey!("EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v").to_bytes();
        assert!(is_stable_mint(&usdc));
        assert!(!is_stable_mint(&[7u8; 32]));
    }

    #[test]
    fn every_listed_mint_matches_and_is_distinct() {
        assert_eq!(STABLE_MINTS.len(), 32);
        for (i, a) in STABLE_MINTS.iter().enumerate() {
            assert!(is_stable_mint(&a.to_bytes()));
            for b in &STABLE_MINTS[i + 1..] {
                assert_ne!(a, b);
            }
        }
    }

    #[test]
    fn legs() {
        let s = STABLE_PYTH_FEED_IDS[0];
        let o = [9u8; 32];
        assert!(oracle_primary_leg_is_stable(1, &[s, [0; 32], [0; 32]]));
        assert!(oracle_primary_leg_is_stable(2, &[s, STABLE_PYTH_FEED_IDS[1], [0; 32]]));
        assert!(!oracle_primary_leg_is_stable(2, &[o, s, [0; 32]]));
        assert!(oracle_primary_leg_is_stable(2, &[s, o, [0; 32]]), "dummy-leg cross");
        assert!(oracle_primary_leg_is_stable(3, &[s, o, [8; 32]]));
        assert!(!oracle_primary_leg_is_stable(1, &[o, s, [0; 32]]));
        assert!(!oracle_primary_leg_is_stable(0, &[s, s, s]));
    }

    #[test]
    fn feeds_distinct() {
        for (i, a) in STABLE_PYTH_FEED_IDS.iter().enumerate() {
            for b in &STABLE_PYTH_FEED_IDS[i + 1..] {
                assert_ne!(a, b);
            }
        }
    }
}
